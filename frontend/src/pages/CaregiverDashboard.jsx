import { useEffect, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import {
  Heart, LayoutDashboard, Users, BookHeart,
  Clock, MessageCircle, Activity, Settings,
  Plus, Search, Bell, ChevronRight, Trash2,
  Pencil, ArrowLeft, CalendarDays, X, RefreshCw
} from 'lucide-react';

import '../App.css';

import {
  getMemories,
  createMemory,
  updateMemory,
  deleteMemory,
  getReminders,
  createReminder,
  updateReminder,
  deleteReminder,
  getConversations,
  getConversationSummary,
  getLinkedPatients,
  redeemLinkingCode,
  selectPatient
} from '../services/api';

function CaregiverDashboard() {
  const navigate = useNavigate();

  const [activeSection, setActiveSection] = useState('overview');
  const [search, setSearch] = useState('');

  const [memories, setMemories] = useState([]);
  const [reminders, setReminders] = useState([]);

  const [loading, setLoading] = useState(true);
  const [apiError, setApiError] = useState('');

  // Conversation state
  const [conversations, setConversations] = useState([]);
  const [conversationSummary, setConversationSummary] = useState(null);
  const [conversationLoading, setConversationLoading] = useState(false);
  const [conversationError, setConversationError] = useState('');

  const [linkedPatients, setLinkedPatients] = useState([]);

  const selectedPatient =
    linkedPatients.find(
      patient => patient.id === localStorage.getItem('selectedPatientId')
    ) || linkedPatients[0] || null;
  const [linkCode, setLinkCode] = useState('');
  const [linking, setLinking] = useState(false);
  const [linkError, setLinkError] = useState('');

  const [showModal, setShowModal] = useState(false);
  const [modalType, setModalType] = useState('memory');
  const [editingId, setEditingId] = useState(null);

  const [form, setForm] = useState({
    title: '',
    description: '',
    category: 'People',
    time: '01:00'
  });

  useEffect(() => {
    let active = true;

    const loadDashboardData = async () => {
      setLoading(true);
      setApiError('');
      try {
        const result = await getLinkedPatients();
        const patients = result.patients || [];
        if (!active) return;
        setLinkedPatients(patients);

        if (patients.length === 0) {
          setMemories([]);
          setReminders([]);
          return;
        }

        const savedId = localStorage.getItem('selectedPatientId');
        const selected = patients.find(patient => patient.id === savedId) || patients[0];
        selectPatient(selected.id);

        const [memoryResult, reminderResult] = await Promise.allSettled([
          getMemories(),
          getReminders()
        ]);
        if (!active) return;

        if (memoryResult.status === 'fulfilled') setMemories(memoryResult.value);
        else setApiError('Could not load patient memories.');

        if (reminderResult.status === 'fulfilled') setReminders(reminderResult.value);
        else setApiError(previous => previous ? `${previous} Could not load reminders.` : 'Could not load patient reminders.');
      } catch (error) {
        console.error('Failed to load caregiver dashboard:', error);
        if (active) setApiError('Unable to load linked patients. Please check the backend and try again.');
      } finally {
        if (active) setLoading(false);
      }
    };

    loadDashboardData();
    return () => { active = false; };
  }, []);

  const handleLinkPatient = async (event) => {
    event.preventDefault();
    if (!/^\d{8}$/.test(linkCode.trim())) {
      setLinkError('Enter the 8-digit code generated by the patient.');
      return;
    }

    try {
      setLinking(true);
      setLinkError('');
      await redeemLinkingCode(linkCode.trim());
      const result = await getLinkedPatients();
      const patients = result.patients || [];
      setLinkedPatients(patients);

      if (patients.length) {
        selectPatient(patients[0].id);
        const [memoryResult, reminderResult] = await Promise.allSettled([
          getMemories(), getReminders()
        ]);
        if (memoryResult.status === 'fulfilled') setMemories(memoryResult.value);
        if (reminderResult.status === 'fulfilled') setReminders(reminderResult.value);
        setLinkCode('');
      }
    } catch (error) {
      setLinkError(error.response?.data?.detail || 'Could not connect to this patient. Check the code and try again.');
    } finally {
      setLinking(false);
    }
  };

  const renderLinkPatient = () => (
    <section className="care-card profile-placeholder">
      <Users size={40} />
      <h2>Connect with a patient</h2>
      <p>Ask the patient to open their dashboard, generate a caregiver linking code, and share the 8-digit code with you. It expires after 15 minutes and can only be used once.</p>
      <form onSubmit={handleLinkPatient} className="care-link-form">
        <label htmlFor="patient-link-code">Patient linking code</label>
        <input
          id="patient-link-code"
          type="text"
          inputMode="numeric"
          autoComplete="one-time-code"
          maxLength={8}
          value={linkCode}
          onChange={event => setLinkCode(event.target.value.replace(/\D/g, '').slice(0, 8))}
          placeholder="Enter 8-digit code"
          required
        />
        {linkError && <p className="care-api-error" role="alert">{linkError}</p>}
        <button className="care-primary-button" type="submit" disabled={linking || linkCode.length !== 8}>
          {linking ? 'Connecting...' : 'Connect patient'}
        </button>
      </form>
    </section>
  );

  // Load conversation data when the caregiver opens Conversations
  const loadConversationData = async () => {
    try {
      setConversationLoading(true);
      setConversationError('');

      const [historyData, summaryData] = await Promise.all([
        getConversations(),
        getConversationSummary()
      ]);

      setConversations(historyData.conversations || []);
      setConversationSummary(summaryData);
    } catch (error) {
      console.error('Failed to load conversations:', error);
      setConversationError(
        'Unable to load conversation history. Please check the backend and try again.'
      );
    } finally {
      setConversationLoading(false);
    }
  };

  useEffect(() => {
    if (activeSection === 'conversations') {
      loadConversationData();
    }
  }, [activeSection]);

  const formatTime = (time) => {
    if (!time) return '';

    const [hours, minutes] = time.split(':').map(Number);
    const period = hours >= 12 ? 'PM' : 'AM';
    const displayHours = hours % 12 || 12;

    return `${displayHours}:${String(minutes).padStart(2, '0')} ${period}`;
  };

  const formatDateTime = (value) => {
    if (!value) return 'Date unavailable';

    const date = new Date(value);

    if (Number.isNaN(date.getTime())) {
      return 'Date unavailable';
    }

    return date.toLocaleString('en-IN', {
      day: 'numeric',
      month: 'short',
      year: 'numeric',
      hour: 'numeric',
      minute: '2-digit'
    });
  };

  const sections = [
    { id: 'overview', label: 'Overview', icon: LayoutDashboard },
    { id: 'profile', label: 'Patient profile', icon: Users },
    { id: 'memories', label: 'Memory profile', icon: BookHeart },
    { id: 'reminders', label: 'Reminders', icon: Clock },
    { id: 'conversations', label: 'Conversations', icon: MessageCircle }
  ];

  const openModal = (type, item = null) => {
    setModalType(type);
    setEditingId(item?.id ?? null);

    if (item) {
      setForm({
        title: item.title,
        description: item.description,
        category: item.category || 'People',
        time: item.time || '01:00'
      });
    } else {
      setForm({
        title: '',
        description: '',
        category: 'People',
        time: '01:00'
      });
    }

    setShowModal(true);
  };

  const saveItem = async (e) => {
    e.preventDefault();

    try {
      if (modalType === 'memory') {
        const payload = {
          title: form.title.trim(),
          description: form.description.trim(),
          category: form.category
        };

        if (editingId) {
          const updatedMemory = await updateMemory(editingId, payload);

          setMemories(prev =>
            prev.map(memory =>
              memory.id === editingId ? updatedMemory : memory
            )
          );
        } else {
          const newMemory = await createMemory(payload);
          setMemories(prev => [newMemory, ...prev]);
        }
      } else {
        const payload = {
          title: form.title.trim(),
          description: form.description.trim(),
          time: form.time
        };

        if (editingId) {
          const updatedReminder = await updateReminder(editingId, payload);

          setReminders(prev =>
            prev.map(reminder =>
              reminder.id === editingId ? updatedReminder : reminder
            )
          );
        } else {
          const newReminder = await createReminder(payload);

          setReminders(prev =>
            [...prev, newReminder].sort((a, b) =>
              a.time.localeCompare(b.time)
            )
          );
        }
      }

      setShowModal(false);
      setEditingId(null);
    } catch (error) {
      console.error('Failed to save item:', error);

      window.alert(
        error.response?.data?.detail ||
        'Could not save this item. Please try again.'
      );
    }
  };

  const deleteItem = async (type, id) => {
    if (!window.confirm('Are you sure you want to delete this item?')) {
      return;
    }

    try {
      if (type === 'memory') {
        await deleteMemory(id);
        setMemories(prev => prev.filter(memory => memory.id !== id));
      } else {
        await deleteReminder(id);
        setReminders(prev => prev.filter(reminder => reminder.id !== id));
      }
    } catch (error) {
      console.error('Failed to delete item:', error);

      window.alert(
        error.response?.data?.detail ||
        'Could not delete this item. Please try again.'
      );
    }
  };

  const filteredMemories = memories.filter(item =>
    `${item.title} ${item.description} ${item.category}`
      .toLowerCase()
      .includes(search.toLowerCase())
  );

  const renderOverview = () => (
    <>
      <div className="care-welcome">
        <div>
          <span className="care-eyebrow">CAREGIVER SPACE</span>
          <h1>Your care overview</h1>
          <p>Everything you need to support a meaningful day.</p>
        </div>

        <div className="care-date">
          <CalendarDays size={19} />
          {new Date().toLocaleDateString('en-IN', {
            day: 'numeric',
            month: 'long',
            year: 'numeric'
          })}
        </div>
      </div>

      <div className="care-stats">
        <div className="care-stat-card">
          <div className="stat-icon green"><Clock /></div>
          <span>Scheduled reminders</span>
          <h2>{reminders.length}</h2>
          <p>Daily routines</p>
        </div>

        <div className="care-stat-card">
          <div className="stat-icon purple"><BookHeart /></div>
          <span>Saved memories</span>
          <h2>{memories.length}</h2>
          <p>Personal memory records</p>
        </div>

      </div>

      <div className="care-content-grid">
        <section className="care-card">
          <div className="care-card-heading">
            <div>
              <h2>Patient information</h2>
              <p>Basic profile overview</p>
            </div>
            <Users size={22} />
          </div>

          <div className="patient-profile-preview">
            <div className="patient-profile-avatar">
              <Users size={32} />
            </div>
            <div>
              <h3>{selectedPatient?.name || 'Patient profile'}</h3>
              <p>{selectedPatient?.email || 'Patient information unavailable'}</p>
            </div>
          </div>

          <button
            className="care-link-button"
            onClick={() => setActiveSection('profile')}
          >
            View profile <ChevronRight size={18} />
          </button>
        </section>

        <section className="care-card">
          <div className="care-card-heading">
            <div>
              <h2>Upcoming reminders</h2>
              <p>Scheduled daily activities</p>
            </div>
            <Clock size={22} />
          </div>

          {reminders.slice(0, 3).map(item => (
            <div className="overview-reminder" key={item.id}>
              <div>
                <strong>{item.title}</strong>
                <p>{item.description}</p>
              </div>
              <span>{formatTime(item.time)}</span>
            </div>
          ))}

          <button
            className="care-link-button"
            onClick={() => setActiveSection('reminders')}
          >
            Manage reminders <ChevronRight size={18} />
          </button>
        </section>
      </div>

    </>
  );

  const renderMemories = () => (
    <>
      <div className="care-welcome">
        <div>
          <span className="care-eyebrow">PERSONAL CONNECTIONS</span>
          <h1>Memory profile</h1>
          <p>Keep familiar people, places and special moments close.</p>
        </div>

        <button
          className="care-primary-button"
          onClick={() => openModal('memory')}
        >
          <Plus size={19} /> Add memory
        </button>
      </div>

      <div className="care-search">
        <Search size={19} />
        <input
          value={search}
          onChange={e => setSearch(e.target.value)}
          placeholder="Search memories..."
        />
      </div>

      <div className="memory-management-grid">
        {filteredMemories.map(item => (
          <article className="memory-management-card" key={item.id}>
            <span className="memory-category">{item.category}</span>
            <h3>{item.title}</h3>
            <p>{item.description}</p>

            <div className="management-actions">
              <button onClick={() => openModal('memory', item)}>
                <Pencil size={17} /> Edit
              </button>

              <button onClick={() => deleteItem('memory', item.id)}>
                <Trash2 size={17} /> Delete
              </button>
            </div>
          </article>
        ))}

        {filteredMemories.length === 0 && (
          <p>No matching memories found.</p>
        )}
      </div>
    </>
  );

  const renderReminders = () => (
    <>
      <div className="care-welcome">
        <div>
          <span className="care-eyebrow">DAILY ROUTINES</span>
          <h1>Manage reminders</h1>
          <p>Help maintain familiar daily routines.</p>
        </div>

        <button
          className="care-primary-button"
          onClick={() => openModal('reminder')}
        >
          <Plus size={19} /> Add reminder
        </button>
      </div>

      <section className="care-card">
        {reminders.length === 0 && <p>No reminders added yet.</p>}

        {reminders.map(item => (
          <div className="managed-reminder" key={item.id}>
            <div className="reminder-time-block">
              <Clock size={20} />
              <span>{formatTime(item.time)}</span>
            </div>

            <div className="managed-reminder-info">
              <h3>{item.title}</h3>
              <p>{item.description}</p>
            </div>

            <div className="management-actions">
              <button onClick={() => openModal('reminder', item)}>
                <Pencil size={17} />
              </button>
              <button onClick={() => deleteItem('reminder', item.id)}>
                <Trash2 size={17} />
              </button>
            </div>
          </div>
        ))}
      </section>
    </>
  );

  const renderProfile = () => (
    <>
      <div className="care-welcome">
        <div>
          <span className="care-eyebrow">PATIENT DETAILS</span>
          <h1>Patient profile</h1>
          <p>View the basic information of your linked patient.</p>
        </div>
      </div>

      {!selectedPatient ? (
        <section className="care-card profile-placeholder">
          <Users size={40} />
          <h2>No patient selected</h2>
          <p>Connect a patient to view their profile information.</p>
        </section>
      ) : (
        <section className="care-card">
          <div className="care-card-heading">
            <div>
              <h2>Personal information</h2>
              <p>Details retrieved from the registered patient account.</p>
            </div>
            <Users size={22} />
          </div>

          <div className="patient-profile-preview">
            <div className="patient-profile-avatar">
              <Users size={32} />
            </div>
            <div>
              <h3>{selectedPatient.name || 'Patient'}</h3>
              <p>Linked patient</p>
            </div>
          </div>

          <div className="profile-details">
            <div className="profile-detail-item">
              <span>Full name</span>
              <strong>{selectedPatient.name || 'Not available'}</strong>
            </div>

            <div className="profile-detail-item">
              <span>Email address</span>
              <strong>{selectedPatient.email || 'Not available'}</strong>
            </div>

            <div className="profile-detail-item">
              <span>Patient ID</span>
              <strong>{selectedPatient.id}</strong>
            </div>

            <div className="profile-detail-item">
              <span>Linked on</span>
              <strong>
                {selectedPatient.linked_at
                  ? new Date(selectedPatient.linked_at).toLocaleDateString(
                      'en-IN',
                      {
                        day: 'numeric',
                        month: 'long',
                        year: 'numeric'
                      }
                    )
                  : 'Not available'}
              </strong>
            </div>
          </div>
        </section>
      )}
    </>
  );

  const renderConversations = () => (
    <>
      <div className="care-welcome">
        <div>
          <span className="care-eyebrow">INTERACTION HISTORY</span>
          <h1>Conversations</h1>
          <p>Review previous interactions with the AI companion.</p>
        </div>

        <button
          className="care-primary-button"
          onClick={loadConversationData}
          disabled={conversationLoading}
        >
          <RefreshCw size={17} />
          {conversationLoading ? 'Refreshing...' : 'Refresh'}
        </button>
      </div>

      {conversationLoading && (
        <section className="care-card">
          <p className="care-api-message">Loading conversation history...</p>
        </section>
      )}

      {!conversationLoading && conversationError && (
        <section className="care-card">
          <p className="care-api-error" role="alert">
            {conversationError}
          </p>
        </section>
      )}

      {!conversationLoading && !conversationError && (
        <>
          {!conversationSummary || conversations.length === 0 ? (
            <section className="care-card profile-placeholder">
              <MessageCircle size={40} />
              <h2>No saved conversations yet</h2>
              <p>
                Conversation history and summaries will appear here
                after the patient interacts with the AI companion.
              </p>
            </section>
          ) : (
            <>
              <div className="care-stats">
                <div className="care-stat-card">
                  <div className="stat-icon green">
                    <MessageCircle />
                  </div>
                  <span>Total exchanges</span>
                  <h2>{conversationSummary.total_exchanges}</h2>
                  <p>Saved interactions</p>
                </div>

                <div className="care-stat-card">
                  <div className="stat-icon purple">
                    <Activity />
                  </div>
                  <span>Analysed exchanges</span>
                  <h2>{conversationSummary.analysed_exchanges}</h2>
                  <p>Classifier-processed messages</p>
                </div>
              </div>

              <section className="care-card">
                <div className="care-card-heading">
                  <div>
                    <h2>Conversation summary</h2>
                    <p>A narrative overview of recent interactions</p>
                  </div>
                  <MessageCircle size={22} />
                </div>

                <p>{conversationSummary.summary}</p>
              </section>

              <div className="care-content-grid">
                <section className="care-card">
                  <div className="care-card-heading">
                    <div>
                      <h2>Common intents</h2>
                      <p>Topics identified in conversations</p>
                    </div>
                    <Activity size={22} />
                  </div>

                  {conversationSummary.common_intents?.length > 0 ? (
                    conversationSummary.common_intents.map(item => (
                      <div className="activity-record" key={item.intent}>
                        <div>
                          <strong>
                            {item.intent.replaceAll('_', ' ')}
                          </strong>
                        </div>
                        <span className="activity-status">{item.count}</span>
                      </div>
                    ))
                  ) : (
                    <p>No intent data available.</p>
                  )}
                </section>

                <section className="care-card">
                  <div className="care-card-heading">
                    <div>
                      <h2>Emotion observations</h2>
                      <p>Automated predictions from recent messages</p>
                    </div>
                    <Heart size={22} />
                  </div>

                  {conversationSummary.detected_emotions?.length > 0 ? (
                    conversationSummary.detected_emotions.map(item => (
                      <div className="activity-record" key={item.emotion}>
                        <div>
                          <strong>{item.emotion}</strong>
                        </div>
                        <span className="activity-status">{item.count}</span>
                      </div>
                    ))
                  ) : (
                    <p>No non-neutral emotion predictions available.</p>
                  )}

                  {conversationSummary.emotion_observations && (
                    <p>{conversationSummary.emotion_observations}</p>
                  )}

                  <p className="profile-note">
                    These are automated classifier predictions, not
                    clinical assessments or diagnoses. They should be
                    interpreted alongside the actual conversation.
                  </p>
                </section>
              </div>

              <section className="care-card">
                <div className="care-card-heading">
                  <div>
                    <h2>Caregiver follow-up</h2>
                    <p>Messages that may deserve additional attention</p>
                  </div>
                  <Heart size={22} />
                </div>

                {conversationSummary.follow_up_messages?.length > 0 ? (
                  conversationSummary.follow_up_messages.map((item, index) => (
                    <div className="activity-record" key={`${item.message}-${index}`}>
                      <div>
                        <p>{item.message}</p>
                        <div className="management-actions">
                          {item.categories?.map(category => (
                            <span className="memory-category" key={category}>
                              {category.replaceAll('_', ' ')}
                            </span>
                          ))}
                        </div>
                        {item.created_at && (
                          <p className="profile-note">
                            {formatDateTime(item.created_at)}
                          </p>
                        )}
                      </div>
                    </div>
                  ))
                ) : (
                  <p>No messages were flagged for follow-up in the analysed exchanges.</p>
                )}

                <p className="profile-note">
                  Follow-up flags are based on simple keyword matching. They
                  are prompts for caregiver review, not clinical risk assessments.
                </p>
              </section>

              <section className="care-card">
                <div className="care-card-heading">
                  <div>
                    <h2>Key messages</h2>
                    <p>Recent messages from the patient</p>
                  </div>
                  <MessageCircle size={22} />
                </div>

                {conversationSummary.key_messages?.length > 0 ? (
                  conversationSummary.key_messages.map((message, index) => (
                    <div className="activity-record" key={index}>
                      <div><p>{message}</p></div>
                    </div>
                  ))
                ) : (
                  <p>No key messages available.</p>
                )}
              </section>

              <section className="care-card">
                <div className="care-card-heading">
                  <div>
                    <h2>Conversation history</h2>
                    <p>Previous patient and AI companion exchanges</p>
                  </div>
                  <MessageCircle size={22} />
                </div>

                {conversations.map(item => (
                  <article
                    key={item.id}
                    style={{
                      padding: '18px 0',
                      borderBottom: '1px solid #e9e9e9'
                    }}
                  >
                    <div
                      style={{
                        display: 'flex',
                        justifyContent: 'space-between',
                        alignItems: 'center',
                        gap: '12px',
                        flexWrap: 'wrap',
                        marginBottom: '12px'
                      }}
                    >
                      <strong>{formatDateTime(item.created_at)}</strong>
                      <span className="memory-category">
                        {item.intent?.replaceAll('_', ' ') || 'unknown'}
                      </span>
                    </div>

                    <div
                      style={{
                        background: '#f5f7f6',
                        padding: '12px 15px',
                        borderRadius: '10px',
                        marginBottom: '10px'
                      }}
                    >
                      <strong>Patient</strong>
                      <p style={{ marginBottom: 0 }}>{item.message}</p>
                    </div>

                    <div
                      style={{
                        background: '#f0f5ff',
                        padding: '12px 15px',
                        borderRadius: '10px'
                      }}
                    >
                      <strong>AI companion</strong>
                      <p style={{ marginBottom: 0 }}>{item.response}</p>
                    </div>

                    <div
                      style={{
                        display: 'flex',
                        gap: '8px',
                        flexWrap: 'wrap',
                        marginTop: '10px'
                      }}
                    >
                      <span className="memory-category">
                        Emotion: {item.emotion || 'unknown'}
                      </span>
                      <span className="memory-category">
                        Intent confidence: {
                          typeof item.intent_confidence === 'number'
                            ? `${(item.intent_confidence * 100).toFixed(1)}%`
                            : 'N/A'
                        }
                      </span>
                    </div>
                  </article>
                ))}
              </section>
            </>
          )}
        </>
      )}
    </>
  );



  const sectionContent = {
    overview: renderOverview,
    profile: renderProfile,
    memories: renderMemories,
    reminders: renderReminders,
    conversations: renderConversations
  };

  return (
    <div className="caregiver-interface">

      <aside className="care-sidebar">
        <div className="care-logo">
          <div><Heart size={23} /></div>
          <span>DementiaCare</span>
        </div>

        <p className="sidebar-label">WORKSPACE</p>

        <nav className="care-navigation">
          {sections.map(section => {
            const Icon = section.icon;

            return (
              <button
                key={section.id}
                className={activeSection === section.id ? 'selected' : ''}
                onClick={() => {
                  setActiveSection(section.id);
                  setSearch('');
                }}
              >
                <Icon size={20} />
                {section.label}
              </button>
            );
          })}
        </nav>

        <div className="sidebar-bottom">
          <button onClick={() => navigate('/')}>
            <ArrowLeft size={19} />
            Back to home
          </button>

          <div className="care-sidebar-footer">
            <Heart size={16} />
            Built around care.
          </div>
        </div>
      </aside>

      <main className="care-main">

        <header className="care-topbar">
          <div>
            <span>Caregiver workspace</span>
          </div>

          <div className="care-topbar-actions">
            <button aria-label="Notifications">
              <Bell size={20} />
            </button>

            <div className="care-user-avatar">C</div>
          </div>
        </header>

        <div className="care-content">
          {loading && (
            <p className="care-api-message">
              Loading memories and reminders...
            </p>
          )}

          {!loading && (
            <>
              {apiError && <p className="care-api-error" role="alert">{apiError}</p>}
              {linkedPatients.length === 0
                ? renderLinkPatient()
                : sectionContent[activeSection]()}
            </>
          )}
        </div>
      </main>

      {showModal && (
        <div
          className="care-modal-overlay"
          onClick={() => setShowModal(false)}
        >
          <section
            className="care-modal"
            onClick={e => e.stopPropagation()}
          >
            <div className="care-modal-header">
              <h2>
                {editingId ? 'Edit' : 'Add'} {modalType}
              </h2>

              <button
                onClick={() => setShowModal(false)}
                aria-label="Close"
              >
                <X size={21} />
              </button>
            </div>

            <form onSubmit={saveItem}>
              <label>
                Title
                <input
                  required
                  value={form.title}
                  onChange={e =>
                    setForm({ ...form, title: e.target.value })
                  }
                  placeholder="Enter a title"
                />
              </label>

              <label>
                Description
                <textarea
                  required
                  rows="3"
                  value={form.description}
                  onChange={e =>
                    setForm({ ...form, description: e.target.value })
                  }
                  placeholder="Enter details"
                />
              </label>

              {modalType === 'memory' ? (
                <label>
                  Category
                  <select
                    value={form.category}
                    onChange={e =>
                      setForm({ ...form, category: e.target.value })
                    }
                  >
                    <option>People</option>
                    <option>Places</option>
                    <option>Interests</option>
                    <option>Important events</option>
                    <option>Daily routines</option>
                  </select>
                </label>
              ) : (
                <label>
                  Reminder time
                  <input
                    type="time"
                    required
                    value={form.time}
                    onChange={e =>
                      setForm({ ...form, time: e.target.value })
                    }
                  />
                </label>
              )}

              <button
                className="care-primary-button modal-submit"
                type="submit"
              >
                {editingId ? 'Save changes' : 'Add'} {modalType}
              </button>
            </form>
          </section>
        </div>
      )}

    </div>
  );
}

export default CaregiverDashboard;