
import hashlib
import secrets
from datetime import datetime, timedelta, timezone

from bson import ObjectId
from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, Field
from pymongo import ReturnDocument
from pymongo.errors import DuplicateKeyError

from app.database.connection import database
from app.core.dependencies import get_current_user, require_role


router = APIRouter(
    prefix="/api/linking",
    tags=["Patient-Caregiver Linking"]
)

linking_codes = database["linking_codes"]
relationships = database["caregiver_relationships"]
users = database["users"]


class RedeemCodeRequest(BaseModel):
    code: str = Field(..., min_length=8, max_length=8, pattern=r"^[0-9]{8}$")


def hash_code(code: str) -> str:
    return hashlib.sha256(code.encode()).hexdigest()


@router.post("/code")
async def generate_linking_code(
    current_user=Depends(require_role("patient"))
):
    now = datetime.now(timezone.utc)

    # Invalidate any unused codes previously generated by this patient.
    await linking_codes.update_many(
        {
            "patient_user_id": str(current_user["_id"]),
            "used_at": None
        },
        {
            "$set": {"used_at": now}
        }
    )

    code = f"{secrets.randbelow(100_000_000):08d}"

    # Existing demo records retain their original patient ID.
    patient_data_id = current_user.get(
        "legacy_patient_id",
        str(current_user["_id"])
    )

    document = {
        "code_hash": hash_code(code),
        "patient_user_id": str(current_user["_id"]),
        "patient_data_id": patient_data_id,
        "created_at": now,
        "expires_at": now + timedelta(minutes=15),
        "used_at": None
    }
    await linking_codes.create_index(
    "code_hash",
    unique=True
)

    await linking_codes.insert_one(document)

    return {
        "message": "Linking code generated successfully",
        "code": code,
        "expires_in_minutes": 15
    }


@router.post("/redeem")
async def redeem_linking_code(
    request: RedeemCodeRequest,
    current_user=Depends(require_role("caregiver"))
):
    now = datetime.now(timezone.utc)
    code_hash = hash_code(request.code)

    # Check whether this relationship already exists.
    code_record = await linking_codes.find_one({
        "code_hash": code_hash,
        "expires_at": {"$gt": now},
        "used_at": None
    })

    if not code_record:
        raise HTTPException(
            status_code=400,
            detail="Invalid, expired or already-used linking code"
        )
    await relationships.create_index(
    [
        ("patient_user_id", 1),
        ("caregiver_user_id", 1)
    ],
    unique=True
)

    existing_relationship = await relationships.find_one({
        "patient_user_id": code_record["patient_user_id"],
        "caregiver_user_id": str(current_user["_id"])
    })

    if existing_relationship:
        raise HTTPException(
            status_code=409,
            detail="You are already linked to this patient"
        )

    # Atomically consume the code so it cannot be redeemed twice.
    consumed_code = await linking_codes.find_one_and_update(
        {
            "_id": code_record["_id"],
            "code_hash": code_hash,
            "expires_at": {"$gt": now},
            "used_at": None
        },
        {
            "$set": {"used_at": now}
        },
        return_document=ReturnDocument.AFTER
    )

    if not consumed_code:
        raise HTTPException(
            status_code=400,
            detail="This linking code has already been used or expired"
        )

    relationship = {
        "patient_user_id": consumed_code["patient_user_id"],
        "patient_data_id": consumed_code["patient_data_id"],
        "caregiver_user_id": str(current_user["_id"]),
        "created_at": now
    }

    try:
        await relationships.insert_one(relationship)
    except DuplicateKeyError:
        raise HTTPException(
            status_code=409,
            detail="This patient is already linked to your account"
        )

    patient = await users.find_one({
        "_id": ObjectId(consumed_code["patient_user_id"])
    })

    return {
        "message": "Patient linked successfully",
        "patient": {
            "id": consumed_code["patient_user_id"],
            "name": patient.get("name", "Patient") if patient else "Patient"
        }
    }


@router.get("/patients")
async def get_linked_patients(
    current_user=Depends(require_role("caregiver"))
):
    cursor = relationships.find({
        "caregiver_user_id": str(current_user["_id"])
    })

    linked_patients = []

    async for relationship in cursor:
        patient = await users.find_one({
            "_id": ObjectId(relationship["patient_user_id"])
        })

        if patient:
            linked_patients.append({
                "id": str(patient["_id"]),
                "name": patient.get("name"),
                "email": patient.get("email"),
                "linked_at": relationship["created_at"].isoformat()
            })

    return {
        "count": len(linked_patients),
        "patients": linked_patients
    }
